import assert from 'node:assert/strict';
import { textToArticle, inlineMd, numberBlocks, blockText, countWords } from '../gloss/src/lib/article';
import { spanIn, quoteFor } from '../gloss/src/lib/anchor';
import { indexArticle, docPayload } from '../gloss/src/lib/doc';

const article = textToArticle('# 阅读测试\n\n这是一段 **重点**，以及 [原始链接](https://example.com)。\n\n## 第二节\n\n| 项目 | 数量 |\n| --- | --- |\n| 书籍 | 3 |', { origin: 'paste' });
assert.equal(article.title, '阅读测试');
assert.equal(countWords('这是一段中文，没有空格也可以导入阅读。'), 17);
assert.ok(countWords('这是一篇没有空格的中文阅读材料，可以直接导入并保留段落。') >= 20);
assert.ok(article.blocks[0].runs.some(r => r.strong && r.text === '重点'));
assert.ok(article.blocks[0].runs.some(r => r.href === 'https://example.com'));
assert.equal(article.blocks.at(-1)?.type, 'table');
assert.equal(article.blocks.at(-1)?.rows?.[1][1], '3');
assert.ok(inlineMd('\\*原样星号\\*').every(r => !r.em));
const nums = numberBlocks(article.blocks);
assert.equal(nums.size, 2);
const a = { start: { b: 'a', o: 2 }, end: { b: 'b', o: 3 }, quote: '' };
const order = new Map([['a', 0], ['b', 1]]);
assert.deepEqual(spanIn(a, 'a', 8, order), [2, 8]);
assert.deepEqual(spanIn(a, 'b', 9, order), [0, 3]);
assert.equal(quoteFor(a, new Map([['a', 'abcdefgh'], ['b', '123456789']]), order), 'cdefgh\n\n123');
const long = { ...article, blocks: Array.from({ length: 150 }, (_, i) => ({ id: `p${i}`, type: 'p' as const, runs: [{ text: 'x'.repeat(1000) }] })) };
const payload = docPayload(indexArticle(long), 'p149');
assert.equal(payload.partial, true); assert.ok(payload.paras.some(p => p.n === 150));
assert.ok(payload.paras.reduce((n,p)=>n+p.text.length,0) <= 85000);
assert.equal(blockText(article.blocks[0]).includes('重点'), true);
console.log('Original Gloss rich text, table parsing, paragraph numbering, cross-block anchors and model context bounds passed.');
