import assert from 'node:assert/strict';
import { TOPICS } from '../src/data';
import { courseSources, selectNotebookSources, sourceEvidence, sourceScopedTopic, type NotebookSource } from '../src/engine/notebookSources';
import { artifactSlidesHtml, artifactSvg, createStudyArtifact, enrichStudyArtifact, restoreArtifacts, studyArtifactEvidence, type StudioKind } from '../src/engine/studyStudio';
import { buildStudyPrompt, emptyWorkspace, loadWorkspace, saveWorkspace } from '../src/engine/studyWorkspace';

const topic = structuredClone(TOPICS[0]); topic.prep.microLecture.body = 'UNSELECTED_LECTURE';
const sources: NotebookSource[] = [{ id: 'text:one', title: '<script>alert(1)</script>', kind: 'text', content: 'SELECTED_MATERIAL 这是第一份学习材料的具体内容。' }, { id: 'text:two', title: 'Other', kind: 'text', content: 'UNSELECTED_SOURCE' }];
assert.ok(courseSources(topic).length);
assert.equal(selectNotebookSources(sources, []).length, 0);
const selected = selectNotebookSources(sources, ['text:one']);
assert.equal(selected.length, 1);
const evidence = sourceEvidence(selected, 'SELECTED');
const prompt = buildStudyPrompt(topic, 'ask', '', evidence, '', true);
assert.match(prompt, /SELECTED_MATERIAL/);
assert.doesNotMatch(prompt, /UNSELECTED_LECTURE|UNSELECTED_SOURCE/);
const scoped = sourceScopedTopic(topic, selected);
assert.equal(scoped.misconceptions.length, 0);
assert.equal(scoped.checklist.length, 0);
assert.doesNotMatch(scoped.prep.microLecture.body, /UNSELECTED/);
for (const kind of ['report', 'mindmap', 'slides', 'audio', 'video', 'infographic', 'table'] as StudioKind[]) {
  const artifact = createStudyArtifact(kind, 'Course', selected);
  assert.equal(artifact.method, 'extractive');
  assert.equal(artifact.sources.length, 1);
  assert.ok(artifact.sections.every((section) => section.sourceIds.every((id) => id === 'text:one')));
  assert.doesNotMatch(artifactSlidesHtml(artifact), /<script>/);
  assert.doesNotMatch(artifactSvg(artifact), /<script>/);
  assert.equal(restoreArtifacts([artifact]).length, 1);
  assert.equal(restoreArtifacts([{ ...artifact, sections: [{ title: 'Bad', text: 'BAD', sourceIds: ['not-selected'] }] }]).length, 0);
}
assert.throws(() => createStudyArtifact('report', 'Empty', []));
const longSource: NotebookSource = { id: 'text:long', title: 'Long', kind: 'text', content: 'A'.repeat(1900) + '\n\nLATE_PARAGRAPH that must remain in the saved evidence.' };
const longArtifact = createStudyArtifact('report', 'Long', [longSource]);
assert.match(longArtifact.sections[1].text, /LATE_PARAGRAPH/);
assert.match(longArtifact.sources[0].excerpt, /LATE_PARAGRAPH/);
assert.match(restoreArtifacts([longArtifact])[0].sources[0].excerpt, /LATE_PARAGRAPH/);
const longDocument = { ...longSource, content: 'FRONT_MATTER ' + 'a'.repeat(10000) + ' CORE_METHOD ' + 'b'.repeat(10000) + ' CONCLUSION' };
const documentEvidence = studyArtifactEvidence([longDocument]);
assert.ok(documentEvidence[0].excerpt.length <= 8000);
assert.match(documentEvidence[0].excerpt, /CONCLUSION/);
assert.ok(documentEvidence[0].excerpt.includes('b'.repeat(100)), 'AI report must receive material beyond the opening 550 characters');
assert.equal(studyArtifactEvidence([longSource])[0].excerpt, longSource.content, 'short documents retain complete source text');
const map = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (key: string) => map.get(key) ?? null, setItem: (key: string, value: string) => map.set(key, value) } });
const artifact = createStudyArtifact('report', 'Course', selected);
saveWorkspace('alice', 'one', { ...emptyWorkspace(), selectedSourceIds: [], textSources: sources, artifacts: [artifact] });
assert.deepEqual(loadWorkspace('alice', 'one').selectedSourceIds, []);
assert.equal(loadWorkspace('alice', 'one').artifacts?.[0].sections[0].text, artifact.sections[0].text);
assert.equal(loadWorkspace('bob', 'one').artifacts?.length ?? 0, 0);
const originalFetch = globalThis.fetch;
globalThis.fetch = async () => new Response(JSON.stringify({ content: JSON.stringify({ title: 'Valid', sections: [{ title: 'First', text: 'Verified summary', sourceIds: ['text:one'] }] }) }));
const updated = await enrichStudyArtifact(artifact, selected, { mode: 'proxy' } as never, new AbortController().signal);
assert.equal(updated.method, 'model');
globalThis.fetch = async () => new Response(JSON.stringify({ content: JSON.stringify({ sections: [{ title: 'Wrong source', text: 'bad', sourceIds: ['text:two'] }] }) }));
await assert.rejects(enrichStudyArtifact(artifact, selected, { mode: 'proxy' } as never, new AbortController().signal), /引用不完整/);
assert.equal(artifact.method, 'extractive');
await assert.rejects(enrichStudyArtifact(artifact, sources, { mode: 'proxy' } as never, new AbortController().signal), /资料范围已改变/);
globalThis.fetch = originalFetch;
console.log('notebook-workspace: selection isolation, snapshots, safe exports, artifact validation and account persistence passed');
