import assert from 'node:assert/strict';
import { TOPICS } from '../src/data';
import { completeStudyScene, restoreGuidedProgress, studyScenes } from '../src/engine/guidedStudy';
import { emptyWorkspace, loadWorkspace, saveWorkspace } from '../src/engine/studyWorkspace';

const store = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (key: string) => store.get(key) ?? null, setItem: (key: string, value: string) => store.set(key, value) } });
const topic = TOPICS.find((item) => item.topicId === 'attention')!;
const scenes = studyScenes(topic);
assert.ok(scenes.some((scene) => scene.kind === 'explain'));
assert.ok(scenes.some((scene) => scene.kind === 'example'));
assert.ok(scenes.some((scene) => scene.kind === 'quiz'));
assert.equal(scenes.at(-1)?.kind, 'reflect');
let progress = restoreGuidedProgress(scenes);
progress = completeStudyScene(progress, scenes);
assert.equal(progress.completed.length, 1);
assert.equal(progress.activeId, scenes[1].id);
progress = completeStudyScene(progress, scenes, true);
assert.equal(progress.skipped.length, 1);
assert.equal(progress.completed.length, 1, 'skipping does not complete a step');
const current = progress.activeId;
progress.returnId = current;
const state = { ...emptyWorkspace(), guided: progress };
saveWorkspace('alice', topic.topicId, state);
assert.equal(loadWorkspace('alice', topic.topicId).guided?.returnId, current);
assert.equal(loadWorkspace('bob', topic.topicId).guided, undefined);
assert.equal(loadWorkspace('alice', 'different-topic').guided, undefined);
const changed = structuredClone(topic);
changed.prep.microLecture.body += '\n\nRevised material.';
assert.equal(restoreGuidedProgress(studyScenes(changed), progress).completed.length, 0);
assert.equal(restoreGuidedProgress(scenes, { ...progress, activeId: 'invalid', completed: ['invalid'], answers: { invalid: 9 } }).activeId, scenes[0].id);
assert.deepEqual(restoreGuidedProgress(scenes, { ...progress, answers: { invalid: 9 } }).answers, {});
console.log('guided-study: typed scenes, explicit completion, skips, resume, account isolation and changed-material reset passed');
