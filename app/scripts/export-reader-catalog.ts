import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The shelf needs metadata, not the bundled books' full text.
const names = ['on-a-piece-of-chalk', 'on-thinking-for-oneself', 'walden-reading'];
const catalog = names.map((name) => {
  const article = JSON.parse(readFileSync(new URL(`../gloss/src/content/${name}.json`, import.meta.url), 'utf8'));
  const words = article.blocks.reduce((sum: number, block: { runs: { text: string }[] }) => {
    const text = block.runs.map((run) => run.text).join('');
    return sum + (text.match(/\p{Script=Han}/gu)?.length ?? 0)
      + text.replace(/\p{Script=Han}/gu, ' ').split(/\s+/).filter((word) => /[\p{L}\p{N}]/u.test(word)).length;
  }, 0);
  return { id: article.id, title: article.title, author: article.author, published: article.published, dek: article.dek, words };
});
writeFileSync(fileURLToPath(new URL('../gloss/src/lib/sample-catalog.ts', import.meta.url)),
  `// Generated by scripts/export-reader-catalog.ts. Full texts load only when opened.\nexport const SAMPLE_CATALOG = ${JSON.stringify(catalog, null, 2)};\n`);
console.log(`Exported ${catalog.length} lightweight reader sample entries.`);
